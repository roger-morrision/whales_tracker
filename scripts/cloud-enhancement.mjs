import { writeFile } from "node:fs/promises";

const apiKey = process.env.NVIDA_NIM_API_KEY || process.env.NVIDIA_NIM_API_KEY;
const model = process.env.NVIDA_NIM_MODE || process.env.NVIDIA_NIM_MODEL;
const baseUrl = (process.env.NVIDIA_NIM_BASE_URL || "https://integrate.api.nvidia.com/v1").replace(/\/$/, "");

if (!apiKey || !model) {
  throw new Error("NVIDIA NIM credentials are not configured for the cloud enhancement job");
}

// Deliberately send repository metadata only. The cloud job must not upload
// private source files or environment values to an external model provider.
const context = [
  `Repository: ${process.env.GITHUB_REPOSITORY || "unknown"}`,
  `Commit: ${process.env.GITHUB_SHA || "unknown"}`,
  "Application: Next.js Solana analytics dashboard with live market data, wallet UI, alerts, and AI copilot.",
  "Guardrails: no synthetic market data, no automatic trade execution, no secret changes, and all code changes require review.",
  "Baseline checks: ESLint, unit tests, API contract tests, and production build run before this audit.",
].join("\n");

const response = await fetch(`${baseUrl}/chat/completions`, {
  method: "POST",
  headers: {
    Authorization: `Bearer ${apiKey}`,
    "Content-Type": "application/json",
  },
  body: JSON.stringify({
    model,
    temperature: 0.1,
    max_tokens: 900,
    messages: [
      {
        role: "system",
        content: "You are a senior maintainer auditing a Solana analytics Next.js app. Identify one high-value, safe enhancement that can be implemented in a small pull request. Do not recommend trading execution changes, secret handling changes, or synthetic data. Return strict JSON with title and body fields. The body must include problem, proposed change, files, acceptance criteria, and risks.",
      },
      {
        role: "user",
        content: `Audit this repository snapshot and propose the next safe enhancement:\n${context}`,
      },
    ],
  }),
});

if (!response.ok) {
  throw new Error(`NVIDIA NIM request failed (${response.status})`);
}

const payload = await response.json();
const content = payload.choices?.[0]?.message?.content?.trim();
if (!content) throw new Error("NVIDIA NIM returned an empty enhancement proposal");

const jsonText = content.match(/\{[\s\S]*\}/)?.[0];
if (!jsonText) throw new Error("NVIDIA NIM returned a non-JSON enhancement proposal");

const proposal = JSON.parse(jsonText);
if (typeof proposal.title !== "string" || typeof proposal.body !== "string") {
  throw new Error("Enhancement proposal is missing title or body");
}

await writeFile("cloud-enhancement-issue.md", `${proposal.body}\n\n_Generated by the scheduled NVIDIA NIM maintenance audit using model \`${model}\`._\n`);
console.log(proposal.title);
