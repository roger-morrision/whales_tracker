import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";

const apiKey = process.env.NVIDA_NIM_API_KEY || process.env.NVIDIA_NIM_API_KEY;
const model = process.env.NVIDA_NIM_MODE || process.env.NVIDIA_NIM_MODEL;
const baseUrl = (process.env.NVIDIA_NIM_BASE_URL || "https://integrate.api.nvidia.com/v1").replace(/\/$/, "");

if (!apiKey || !model) {
  throw new Error("NVIDIA NIM credentials are not configured for the cloud maintenance job");
}

// This job is explicitly authorized to send the checked-out source to NIM for
// patch generation. Secrets and environment files are always excluded, and
// the workflow validates the patch before opening a draft PR.
const trackedFiles = execFileSync("git", ["ls-files", "src", "tests"], { encoding: "utf8" })
  .split(/\r?\n/)
  .filter((file) => /\.(ts|tsx)$/.test(file))
  .slice(0, 120);
const context = (await Promise.all(trackedFiles.map(async (file) => (
  `\n--- ${file} ---\n${await readFile(file, "utf8")}`
)))).join("").slice(0, 80_000);

const response = await fetch(`${baseUrl}/chat/completions`, {
  method: "POST",
  headers: {
    Authorization: `Bearer ${apiKey}`,
    "Content-Type": "application/json",
  },
  body: JSON.stringify({
    model,
    temperature: 0.1,
    max_tokens: 3_000,
    messages: [
      {
        role: "system",
        content: [
          "You are a senior maintainer for a Next.js Solana analytics app.",
          "Find one small, high-value bug fix or enhancement that is safe to implement now.",
          "Return exactly these markers: TITLE:, BODY:, PATCH:.",
          "PATCH must be a unified diff in a single ```diff fenced block.",
          "The patch may touch at most two files under src/ or tests/.",
          "Never change .env files, secrets, wallet signing, trade execution, or synthetic market data.",
          "If no safe change is clear, return TITLE: No safe change and an empty PATCH block.",
        ].join(" "),
      },
      {
        role: "user",
        content: `Repository ${process.env.GITHUB_REPOSITORY || "unknown"} at ${process.env.GITHUB_SHA || "unknown"}.\n${context}`,
      },
    ],
  }),
});

if (!response.ok) throw new Error(`NVIDIA NIM request failed (${response.status})`);

const payload = await response.json();
const content = payload.choices?.[0]?.message?.content?.trim();
if (!content) throw new Error("NVIDIA NIM returned an empty maintenance proposal");

const title = content.match(/^TITLE:\s*(.+)$/m)?.[1]?.trim() || "Hourly cloud maintenance proposal";
const bodyStart = content.indexOf("BODY:");
const patchStart = content.indexOf("PATCH:");
const body = bodyStart >= 0 && patchStart > bodyStart
  ? content.slice(bodyStart + "BODY:".length, patchStart).trim()
  : "Generated maintenance proposal; inspect the draft PR before merging.";
const patchMatch = content.slice(patchStart >= 0 ? patchStart : content.length).match(/```diff\s*([\s\S]*?)```/i);
const diff = patchMatch?.[1]?.trim() || "";

await writeFile("cloud-maintenance-title.txt", title);
await writeFile("cloud-maintenance.md", `${body}\n\n_Generated by the hourly NVIDIA NIM maintenance job using model \`${model}\`._\n`);
await writeFile("cloud-maintenance.patch", diff ? `${diff}\n` : "");
console.log(title);
